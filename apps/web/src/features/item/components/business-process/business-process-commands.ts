/**
 * Pure editing commands of the business process sidebar. Each takes the latest nodes and
 * returns the next ones, or a string with the reason the command was rejected, so callers can
 * run it inside a state updater and still report the problem.
 */
export type BusinessProcessCommandResult = BusinessProcessNode[] | string

export type ParticipantOrientation = 'horizontal' | 'vertical'

/** Offset of an element added into a selected pool or lane, from its top-left corner. */
const PARTICIPANT_CHILD_OFFSET = { x: 48, y: 48 }

const isWhiteBoxPool = (node?: BusinessProcessNode): node is BusinessProcessNode =>
  node?.data.kind === 'participant' && node.data.participantType === 'pool' && !node.data.blackBox

const lanesOf = (nodes: BusinessProcessNode[], poolId: string) =>
  nodes.filter(
    (node) =>
      node.parentId === poolId &&
      node.data.kind === 'participant' &&
      node.data.participantType === 'lane',
  )

/** Nearest pool containing `node` (or `node` itself when it is a pool). */
export const findPoolAncestor = (node: BusinessProcessNode, nodes: BusinessProcessNode[]) => {
  const visited = new Set<string>()
  let current: BusinessProcessNode | undefined = node

  while (current && !visited.has(current.id)) {
    if (current.data.kind === 'participant' && current.data.participantType === 'pool') {
      return current
    }
    visited.add(current.id)
    const parentId: string | undefined = current.parentId
    current = parentId ? nodes.find((candidate) => candidate.id === parentId) : undefined
  }

  return undefined
}

export const hasInvalidBusinessProcessConnections = (
  edges: BusinessProcessEdge[],
  nodes: BusinessProcessNode[],
) =>
  edges.some((edge) => {
    const edgeKind = edge.data?.kind
    return (
      (edgeKind === 'sequenceFlow' || edgeKind === 'messageFlow') &&
      !isValidBusinessProcessConnection(edge, nodes, edgeKind)
    )
  })

/** Boundary events would snap onto the original's exact spot, so they are not duplicated. */
export const canDuplicateBusinessProcessNode = (node?: BusinessProcessNode) =>
  !!node && !(node.data.kind === 'event' && node.data.context === 'boundary')

export const duplicateBusinessProcessNode = (
  nodes: BusinessProcessNode[],
  nodeId: string,
): BusinessProcessNode[] => {
  if (!canDuplicateBusinessProcessNode(nodes.find((node) => node.id === nodeId))) return nodes
  return duplicateNode(nodes, nodeId, (data) => {
    if (data.kind !== 'gateway') return data
    // The default flow is an outgoing edge of the original gateway, not of the copy.
    const { defaultFlowId: _defaultFlowId, ...gatewayData } = data
    return gatewayData
  })
}

export type AddBusinessProcessNodeOptions = {
  /** Id of the new node; generated by the caller so the command stays pure. */
  id: string
  tool: BusinessProcessNodeTool
  selectedNodeId?: string
  /** Position of a top-level element: the center of the viewport. */
  center: { x: number; y: number }
}

const addLane = (
  nodes: BusinessProcessNode[],
  { id, tool, selectedNodeId }: AddBusinessProcessNodeOptions,
  data: Extract<BusinessProcessNodeData, { kind: 'participant' }>,
): BusinessProcessCommandResult => {
  const selectedNode = nodes.find((node) => node.id === selectedNodeId)
  const pools = nodes.filter(isWhiteBoxPool)
  const pool = selectedNode
    ? findPoolAncestor(selectedNode, nodes)
    : pools.length === 1
      ? pools[0]
      : undefined
  if (!isWhiteBoxPool(pool) || pool.data.kind !== 'participant') {
    return 'Select a white-box pool before adding a lane.'
  }

  const orientation = pool.data.orientation
  const newLane: BusinessProcessNode = {
    id,
    type: tool.nodeType,
    position: { x: 0, y: 0 },
    parentId: pool.id,
    style: { width: tool.width, height: tool.height },
    data: { ...data, orientation },
  }
  const lanes = [...orderParticipantLanes(lanesOf(nodes, pool.id), orientation), newLane]
  const laneMinimums = lanes.map((lane) => minimumParticipantNodeSize(lane, nodes, orientation))
  const poolSize = sizeParticipantContainerForLanes(
    businessProcessNodeSize(pool),
    lanes.length,
    orientation,
    laneMinimums,
  )
  const lanesById = new Map(
    layoutParticipantLanes(
      lanes,
      poolSize,
      orientation,
      Array(lanes.length).fill(1),
      laneMinimums,
    ).map((lane) => [lane.id, lane]),
  )

  return [
    ...nodes.map((node) =>
      node.id === pool.id
        ? { ...node, ...poolSize, style: { ...node.style, ...poolSize } }
        : (lanesById.get(node.id) ?? node),
    ),
    lanesById.get(newLane.id) as BusinessProcessNode,
  ]
}

/**
 * Adds an element created by `tool`. Lanes go into the selected (or only) pool, boundary events
 * onto the selected activity, other elements into the selected participant or the viewport center.
 */
export const addBusinessProcessNode = (
  nodes: BusinessProcessNode[],
  options: AddBusinessProcessNodeOptions,
): BusinessProcessCommandResult => {
  const { id, tool, selectedNodeId, center } = options
  const data = tool.createData()
  const selectedNode = nodes.find((node) => node.id === selectedNodeId)

  if (data.kind === 'participant' && data.participantType === 'lane') {
    return addLane(nodes, options, data)
  }

  const size = { width: tool.width, height: tool.height }

  if (data.kind === 'event' && data.context === 'boundary') {
    if (selectedNode?.data.kind !== 'activity') {
      return 'Select an activity before adding a boundary event.'
    }
    const attachment = attachBoundaryEventToActivity(
      selectedNode.id,
      businessProcessNodeSize(selectedNode),
      size,
    )
    return [
      ...nodes,
      {
        id,
        type: tool.nodeType,
        ...attachment,
        style: size,
        data: { ...data, attachedToId: selectedNode.id },
      },
    ]
  }

  const isPool = data.kind === 'participant' && data.participantType === 'pool'
  const parent = !isPool && selectedNode?.data.kind === 'participant' ? selectedNode : undefined
  if (parent?.data.kind === 'participant' && parent.data.blackBox) {
    return 'Black-box pools cannot contain diagram elements.'
  }

  return [
    ...nodes,
    {
      id,
      type: tool.nodeType,
      position: parent ? PARTICIPANT_CHILD_OFFSET : center,
      ...(parent ? { parentId: parent.id, extent: 'parent' as const } : {}),
      style: size,
      data,
    },
  ]
}

export const updateBusinessProcessNodeData = (
  nodes: BusinessProcessNode[],
  nodeId: string,
  updater: (data: BusinessProcessNodeData) => BusinessProcessNodeData,
): BusinessProcessNode[] =>
  nodes.map((node) => (node.id === nodeId ? { ...node, data: updater(node.data) } : node))

/**
 * Moves an event to another context. A boundary event is attached to the activity it belongs
 * to; leaving the boundary context detaches it next to that activity.
 */
export const changeBusinessProcessEventContext = (
  nodes: BusinessProcessNode[],
  eventId: string,
  context: BusinessProcessEventContext,
): BusinessProcessCommandResult => {
  const event = nodes.find((node) => node.id === eventId)
  if (event?.data.kind !== 'event') return nodes
  const eventData = event.data
  const parent = nodes.find((node) => node.id === event.parentId)

  const contextEventTypes = businessProcessEventTypesByContext[context]
  const eventType = contextEventTypes.includes(eventData.eventType)
    ? eventData.eventType
    : contextEventTypes[0]
  const attachedActivity = nodes.find((node) => node.id === eventData.attachedToId)
  const activity =
    attachedActivity?.data.kind === 'activity'
      ? attachedActivity
      : parent?.data.kind === 'activity'
        ? parent
        : undefined
  if (context === 'boundary' && !activity) {
    return 'Boundary events must be attached to an activity.'
  }

  const attachment =
    context === 'boundary' && activity
      ? attachBoundaryEventToActivity(
          activity.id,
          businessProcessNodeSize(activity),
          businessProcessNodeSize(event),
        )
      : undefined
  const detachment =
    context !== 'boundary' && parent?.data.kind === 'activity'
      ? detachBoundaryEventFromActivity(parent, event.position)
      : undefined
  const attachedToId =
    context === 'boundary'
      ? activity?.id
      : (eventData.attachedToId ?? (parent?.data.kind === 'activity' ? parent.id : undefined))

  return nodes.map((node) =>
    node.id === eventId
      ? {
          ...node,
          ...(attachment ?? detachment ?? {}),
          data: { ...eventData, context, eventType, attachedToId },
        }
      : node,
  )
}

export const changeBusinessProcessEventDefinition = (
  nodes: BusinessProcessNode[],
  eventId: string,
  eventType: BusinessProcessEventType,
): BusinessProcessNode[] =>
  nodes.map((node) =>
    node.id === eventId && node.data.kind === 'event'
      ? { ...node, data: { ...node.data, eventType } }
      : node,
  )

export const attachBusinessProcessBoundaryEvent = (
  nodes: BusinessProcessNode[],
  eventId: string,
  activityId: string,
): BusinessProcessNode[] => {
  const event = nodes.find((node) => node.id === eventId)
  const activity = nodes.find((node) => node.id === activityId)
  if (
    event?.data.kind !== 'event' ||
    event.data.context !== 'boundary' ||
    activity?.data.kind !== 'activity'
  )
    return nodes

  const attachment = attachBoundaryEventToActivity(
    activity.id,
    businessProcessNodeSize(activity),
    businessProcessNodeSize(event),
  )
  return nodes.map((node) =>
    node.id === eventId && node.data.kind === 'event'
      ? { ...node, ...attachment, data: { ...node.data, attachedToId: activityId } }
      : node,
  )
}

/**
 * Rotates the pool of `participantId` (a pool or one of its lanes): the pool swaps its width
 * and height and its lanes are laid out along the new axis, keeping their relative sizes.
 */
export const changeBusinessProcessParticipantOrientation = (
  nodes: BusinessProcessNode[],
  participantId: string,
  orientation: ParticipantOrientation,
): BusinessProcessNode[] => {
  const participant = nodes.find((node) => node.id === participantId)
  if (participant?.data.kind !== 'participant') return nodes

  const pool =
    participant.data.participantType === 'pool' ? participant : findPoolAncestor(participant, nodes)
  if (
    pool?.data.kind !== 'participant' ||
    pool.data.participantType !== 'pool' ||
    pool.data.orientation === orientation
  )
    return nodes

  const lanes = orderParticipantLanes(lanesOf(nodes, pool.id), pool.data.orientation)
  const previousAxis = pool.data.orientation === 'horizontal' ? 'height' : 'width'
  const poolSize = businessProcessNodeSize(pool)
  const laneMinimums = lanes.map((lane) => minimumParticipantNodeSize(lane, nodes, orientation))
  const nextPoolSize = sizeParticipantContainerForLanes(
    { width: poolSize.height, height: poolSize.width },
    lanes.length,
    orientation,
    laneMinimums,
  )
  const lanesById = new Map(
    layoutParticipantLanes(
      lanes,
      nextPoolSize,
      orientation,
      lanes.map((lane) => businessProcessNodeSize(lane)[previousAxis]),
      laneMinimums,
    ).map((lane) => [lane.id, lane]),
  )

  return nodes.map((node) => {
    if (node.id === pool.id && node.data.kind === 'participant') {
      return {
        ...node,
        data: { ...node.data, orientation },
        ...nextPoolSize,
        style: { ...node.style, ...nextPoolSize },
      }
    }
    return lanesById.get(node.id) ?? node
  })
}

export const updateBusinessProcessEdgeData = (
  edges: BusinessProcessEdge[],
  edgeId: string,
  updater: (
    data: NonNullable<BusinessProcessEdge['data']>,
  ) => NonNullable<BusinessProcessEdge['data']>,
): BusinessProcessEdge[] =>
  edges.map((edge) =>
    edge.id === edgeId && edge.data ? { ...edge, data: updater(edge.data) } : edge,
  )
